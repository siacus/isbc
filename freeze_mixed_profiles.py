#!/usr/bin/env python3
"""Freeze and reproducibly sample the frequent Qwen profiles in Mixed.

The profile definitions come from the current Mixed profile-matching report.  For
each retained Qwen profile, the script samples rows without replacement using a
fixed global seed and a profile-specific seed derived with SHA-256.  It writes
one CSV and one Excel workbook per profile, plus a complete membership table and
a manifest that records the inputs, profile definitions, seeds, and file hashes.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import json
import random
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

import pandas as pd


REPO_ROOT = Path(__file__).resolve().parent
DEFAULT_SEED = 1234
DEFAULT_SAMPLE_SIZE = 500
DEFAULT_COMPARISON_DIR = Path(
    "runs/mixed_embedding_comparison/all_fixed_balance_source"
)
DEFAULT_READY = Path("data/mixed/mixed_ready.csv")
DEFAULT_LABELS = Path("data/mixed/mixed_labels.csv")
DEFAULT_ENCODED = Path(
    "runs/mixed_qwen_all_fixed_balance/encoded_mixed_ready_best.csv"
)
DEFAULT_OUTPUT = Path(
    f"runs/mixed_embedding_comparison/frozen_profiles_qwen_seed{DEFAULT_SEED}"
)
INVALID_XML_10 = re.compile(
    "[^\x09\x0A\x0D\x20-\uD7FF\uE000-\uFFFD\U00010000-\U0010FFFF]"
)


@dataclass(frozen=True)
class FrozenProfile:
    rank: int
    profile_id: str
    active_bits: tuple[int, ...]
    expected_documents: int
    expected_share: float

    @property
    def active_bits_text(self) -> str:
        return ",".join(str(bit) for bit in self.active_bits)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--comparison-dir", type=Path, default=DEFAULT_COMPARISON_DIR)
    parser.add_argument("--ready", type=Path, default=DEFAULT_READY)
    parser.add_argument("--labels", type=Path, default=DEFAULT_LABELS)
    parser.add_argument("--encoded", type=Path, default=DEFAULT_ENCODED)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--sample-size", type=int, default=DEFAULT_SAMPLE_SIZE)
    parser.add_argument(
        "--replace",
        action="store_true",
        help=(
            "Replace only artifacts generated by an earlier invocation in the "
            "selected output directory."
        ),
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=DEFAULT_SEED,
        help=f"Global sampling seed (default: {DEFAULT_SEED}).",
    )
    parser.add_argument(
        "--skip-xlsx",
        action="store_true",
        help="Write the CSV artifacts only; useful for deterministic test runs.",
    )
    parser.add_argument(
        "--preview-dir",
        type=Path,
        help="Optional directory for temporary workbook preview images used in visual QA.",
    )
    return parser.parse_args()


def absolute(path: Path) -> Path:
    return path if path.is_absolute() else REPO_ROOT / path


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def relative_to_repo(path: Path) -> str:
    resolved = path.resolve()
    try:
        return str(resolved.relative_to(REPO_ROOT))
    except ValueError:
        return str(resolved)


def parse_active_bits(profile_text: str, model: str) -> tuple[int, ...]:
    for component in profile_text.split(";"):
        key, separator, value = component.strip().partition("=")
        if separator and key == model:
            if not value.strip():
                return ()
            return tuple(sorted(int(item) for item in value.split(",") if item != ""))
    raise ValueError(f"No {model!r} profile in {profile_text!r}")


def derived_seed(global_seed: int, profile: FrozenProfile) -> int:
    payload = (
        f"mixed|qwen|global_seed={global_seed}|rank={profile.rank}|"
        f"bits={profile.active_bits_text}"
    ).encode("utf-8")
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big")


def file_record(path: Path, rows: int | None = None) -> dict[str, object]:
    record: dict[str, object] = {
        "path": relative_to_repo(path),
        "size_bytes": path.stat().st_size,
        "sha256": sha256_file(path),
    }
    if rows is not None:
        record["rows"] = rows
    return record


def require_unique_ids(frame: pd.DataFrame, name: str) -> None:
    if "id" not in frame.columns:
        raise ValueError(f"{name} has no id column")
    duplicated = frame["id"].duplicated(keep=False)
    if duplicated.any():
        examples = frame.loc[duplicated, "id"].head(5).tolist()
        raise ValueError(f"{name} has duplicate ids, including {examples}")


def load_profiles(comparison_dir: Path) -> tuple[dict[str, object], list[FrozenProfile]]:
    profile_dir = comparison_dir / "profile_matching"
    manifest_path = profile_dir / "manifest.json"
    matches_path = profile_dir / "matches.csv"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    reference = str(manifest.get("reference", ""))
    if reference != "qwen":
        raise ValueError(f"Expected Qwen reference profiles, found {reference!r}")

    matches = pd.read_csv(matches_path, dtype=str, keep_default_na=False)
    matches = matches.loc[matches["reference"].eq(reference)].reset_index(drop=True)
    expected_count = int(manifest["reference_profile_count"])
    if len(matches) != expected_count:
        raise ValueError(
            f"Manifest expects {expected_count} Qwen profiles, matches.csv has {len(matches)}"
        )

    profiles: list[FrozenProfile] = []
    for index, row in matches.iterrows():
        rank = index + 1
        profiles.append(
            FrozenProfile(
                rank=rank,
                profile_id=f"P{rank:02d}",
                active_bits=parse_active_bits(row["profiles"], reference),
                expected_documents=int(row["start_docs"]),
                expected_share=float(row["start_share"]),
            )
        )
    return manifest, profiles


def profile_mask(encoded: pd.DataFrame, profile: FrozenProfile, bit_columns: list[str]) -> pd.Series:
    active = {f"bit_{bit:02d}" for bit in profile.active_bits}
    expected = pd.Series(
        [1 if column in active else 0 for column in bit_columns], index=bit_columns
    )
    return encoded[bit_columns].eq(expected, axis="columns").all(axis="columns")


def dataframe_to_csv(frame: pd.DataFrame, path: Path) -> None:
    frame.to_csv(
        path,
        index=False,
        encoding="utf-8",
        lineterminator="\n",
        quoting=csv.QUOTE_MINIMAL,
    )


def dataframe_to_workbook_json(frame: pd.DataFrame, path: Path) -> None:
    payload = {
        "headers": frame.columns.tolist(),
        "rows": frame.to_dict(orient="split")["data"],
    }
    path.write_text(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )


def remove_invalid_xml_characters(frame: pd.DataFrame) -> int:
    """Remove control characters that cannot be represented in an XLSX cell."""
    changed = 0
    string_columns = [
        column
        for column in frame.columns
        if pd.api.types.is_object_dtype(frame[column].dtype)
        or pd.api.types.is_string_dtype(frame[column].dtype)
    ]
    for column in string_columns:
        original = frame[column]
        cleaned = original.map(
            lambda value: INVALID_XML_10.sub("", value) if isinstance(value, str) else value
        )
        changed += int((cleaned != original).sum())
        frame[column] = cleaned
    return changed


def write_readme(
    output_dir: Path,
    profiles: Iterable[dict[str, object]],
    seed: int,
    sample_size: int,
    threshold: float,
    sanitized_cells: int,
) -> None:
    lines = [
        "# Frozen Mixed Qwen profiles",
        "",
        (
            "This directory freezes the frequent Qwen hard-bit profiles displayed in the "
            "current Mixed comparison. Each profile file contains a reproducible random "
            f"sample of {sample_size:,} documents drawn without replacement."
        ),
        "",
        "## Reproducibility",
        "",
        f"- Global seed: `{seed}`",
        "- Sampling algorithm: Python `random.Random.sample`",
        "- Profile-specific seeds: SHA-256 derivations of the global seed, profile rank, and active bits",
        f"- Reference profile threshold: `{threshold:.4%}` of the {111000:,}-document Mixed corpus",
        "- Reference backbone: Qwen",
        "- Exact inputs and output hashes: `manifest.json`",
        "- Frozen Qwen profile definitions: `profile_definition/`",
        "- Complete membership of all frozen profiles: `profile_membership.csv`",
        (
            "- Excel compatibility: XML 1.0-invalid invisible control characters were "
            f"removed from {sanitized_cells:,} source cells before writing both formats"
        ),
        "",
        "The CSV and Excel files for a profile contain the same rows in the same order. "
        "All document texts and labels are Unicode strings: CSV files use UTF-8 and "
        "Excel workbooks use native Unicode cells. All original Mixed label columns "
        "are retained alongside the document text.",
        "",
        "## Profile files",
        "",
        "| Profile | Active bits | Corpus documents | Corpus share | CSV | Excel |",
        "| --- | --- | ---: | ---: | --- | --- |",
    ]
    for profile in profiles:
        lines.append(
            "| {profile_id} | {active_bits} | {documents:,} | {share:.4%} | "
            "[{csv}]({csv}) | [{xlsx}]({xlsx}) |".format(**profile)
        )
    lines.extend(
        [
            "",
            "## Regenerate",
            "",
            "From the repository root:",
            "",
            "```bash",
            "python freeze_mixed_profiles.py",
            "```",
            "",
            "The script deliberately refuses to overwrite a non-empty output directory. "
            "Choose a new `--output-dir` when changing the seed or sample size.",
            "",
        ]
    )
    (output_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    args = parse_args()
    if args.sample_size <= 0:
        raise ValueError("--sample-size must be positive")

    comparison_dir = absolute(args.comparison_dir)
    ready_path = absolute(args.ready)
    labels_path = absolute(args.labels)
    encoded_path = absolute(args.encoded)
    output_dir = absolute(args.output_dir)

    if output_dir.exists() and any(output_dir.iterdir()):
        if not args.replace:
            raise FileExistsError(
                f"Refusing to overwrite non-empty output directory: {output_dir}"
            )
        generated_names = {
            "README.md",
            "manifest.json",
            "profile_membership.csv",
        }
        for path in output_dir.iterdir():
            if path.is_dir() and path.name == "profile_definition":
                shutil.rmtree(path)
                continue
            generated_profile = (
                path.is_file()
                and (
                    re.fullmatch(r"profile_\d+\.(?:csv|xlsx)", path.name)
                    or re.fullmatch(r"\.profile_\d+\.workbook\.json", path.name)
                )
            )
            if path.name in generated_names or generated_profile:
                path.unlink()
        remaining = list(output_dir.iterdir())
        if remaining:
            raise FileExistsError(
                "Refusing to replace a directory containing non-generated files: "
                + ", ".join(path.name for path in remaining)
            )
    output_dir.mkdir(parents=True, exist_ok=True)

    profile_manifest, profiles = load_profiles(comparison_dir)
    profile_definition_dir = output_dir / "profile_definition"
    profile_definition_dir.mkdir(parents=True, exist_ok=False)
    frozen_profile_manifest = profile_definition_dir / "manifest.json"
    frozen_profile_matches = profile_definition_dir / "matches.csv"
    shutil.copy2(
        comparison_dir / "profile_matching" / "manifest.json",
        frozen_profile_manifest,
    )
    shutil.copy2(
        comparison_dir / "profile_matching" / "matches.csv",
        frozen_profile_matches,
    )
    ready = pd.read_csv(ready_path, dtype=str, keep_default_na=False)
    labels = pd.read_csv(labels_path, dtype=str, keep_default_na=False)
    encoded_header = pd.read_csv(encoded_path, nrows=0)
    bit_columns = sorted(
        [column for column in encoded_header.columns if column.startswith("bit_")]
    )
    if not bit_columns:
        raise ValueError(f"No bit columns found in {encoded_path}")
    encoded = pd.read_csv(
        encoded_path,
        usecols=["id", *bit_columns],
        dtype={"id": str, **{column: "int8" for column in bit_columns}},
        keep_default_na=False,
    )

    require_unique_ids(ready, "Mixed ready input")
    require_unique_ids(labels, "Mixed labels")
    require_unique_ids(encoded, "Qwen encoded input")
    ready_ids = set(ready["id"])
    if ready_ids != set(labels["id"]) or ready_ids != set(encoded["id"]):
        raise ValueError("Mixed ready, labels, and encoded inputs do not have identical ids")
    if len(ready) != int(profile_manifest["n_documents"]):
        raise ValueError(
            f"Profile manifest has {profile_manifest['n_documents']} documents, "
            f"but Mixed ready has {len(ready)}"
        )
    invalid_bits = {
        int(value)
        for value in pd.unique(encoded[bit_columns].to_numpy().ravel())
        if int(value) not in (0, 1)
    }
    if invalid_bits:
        raise ValueError(f"Encoded bit columns contain non-binary values: {invalid_bits}")

    ready = ready.reset_index(drop=True)
    ready.insert(0, "corpus_row", range(1, len(ready) + 1))
    labels_without_duplicate_id = labels.drop(columns=["id"])
    combined = ready.merge(labels, on="id", how="left", validate="one_to_one", sort=False)
    if len(combined) != len(ready) or combined[labels_without_duplicate_id.columns].isna().any().any():
        raise ValueError("Failed to attach every Mixed label row")
    sanitized_cells = remove_invalid_xml_characters(combined)
    encoded = ready[["id"]].merge(encoded, on="id", validate="one_to_one", sort=False)

    membership_frames: list[pd.DataFrame] = []
    manifest_profiles: list[dict[str, object]] = []
    readme_profiles: list[dict[str, object]] = []
    threshold = float(profile_manifest["min_reference_profile_share"])

    for profile in profiles:
        mask = profile_mask(encoded, profile, bit_columns)
        member_positions = mask[mask].index.tolist()
        actual_documents = len(member_positions)
        actual_share = actual_documents / len(encoded)
        if actual_documents != profile.expected_documents:
            raise ValueError(
                f"{profile.profile_id}: expected {profile.expected_documents} documents, "
                f"reconstructed {actual_documents}"
            )
        if abs(actual_share - profile.expected_share) > 0.00005:
            raise ValueError(
                f"{profile.profile_id}: expected displayed share {profile.expected_share}, "
                f"reconstructed {actual_share}"
            )
        if actual_documents < args.sample_size:
            raise ValueError(
                f"{profile.profile_id} has {actual_documents} documents, fewer than "
                f"the requested sample of {args.sample_size}"
            )

        local_seed = derived_seed(args.seed, profile)
        selected_positions = random.Random(local_seed).sample(
            member_positions, args.sample_size
        )
        profile_code = "".join(
            "1" if index in profile.active_bits else "0" for index in range(len(bit_columns))
        )
        metadata = {
            "profile_id": profile.profile_id,
            "profile_rank": profile.rank,
            "profile_code": profile_code,
            "active_bits": profile.active_bits_text,
            "profile_size": actual_documents,
            "profile_share": actual_share,
            "global_seed": args.seed,
            "derived_seed": str(local_seed),
        }

        sample = combined.iloc[selected_positions].copy()
        sample.insert(0, "sample_order", range(1, args.sample_size + 1))
        for column, value in reversed(list(metadata.items())):
            sample.insert(0, column, value)
        csv_name = f"profile_{profile.rank:02d}.csv"
        xlsx_name = f"profile_{profile.rank:02d}.xlsx"
        csv_path = output_dir / csv_name
        dataframe_to_csv(sample, csv_path)
        if not args.skip_xlsx:
            dataframe_to_workbook_json(
                sample, output_dir / f".profile_{profile.rank:02d}.workbook.json"
            )

        membership = combined.iloc[member_positions][["corpus_row", "id"]].copy()
        for column, value in reversed(list(metadata.items())):
            membership.insert(0, column, value)
        membership_frames.append(membership)

        manifest_profiles.append(
            {
                **metadata,
                "active_bits": list(profile.active_bits),
                "sample_size": args.sample_size,
                "csv": file_record(csv_path, rows=args.sample_size),
                "xlsx": {"path": relative_to_repo(output_dir / xlsx_name)},
                "sample_id_sha256": hashlib.sha256(
                    "\n".join(sample["id"].tolist()).encode("utf-8")
                ).hexdigest(),
            }
        )
        readme_profiles.append(
            {
                "profile_id": profile.profile_id,
                "active_bits": profile.active_bits_text,
                "documents": actual_documents,
                "share": actual_share,
                "csv": csv_name,
                "xlsx": xlsx_name,
            }
        )

    membership = pd.concat(membership_frames, ignore_index=True)
    membership_path = output_dir / "profile_membership.csv"
    dataframe_to_csv(membership, membership_path)

    manifest_path = output_dir / "manifest.json"
    manifest: dict[str, object] = {
        "schema_version": 1,
        "dataset": "mixed",
        "reference_backbone": "qwen",
        "profile_definition": (
            "Exact 16-bit Qwen hard-code profiles retained by the current Mixed "
            "profile-matching report"
        ),
        "profile_threshold": threshold,
        "n_documents": len(combined),
        "n_profiles": len(profiles),
        "sample_size_per_profile": args.sample_size,
        "sampling": {
            "without_replacement": True,
            "global_seed": args.seed,
            "default_seed_in_script": DEFAULT_SEED,
            "algorithm": "Python random.Random.sample",
            "derived_seed": (
                "first 64 bits of SHA-256 over dataset, backbone, global seed, "
                "profile rank, and active bits"
            ),
        },
        "text_sanitization": {
            "rule": "Remove characters forbidden by XML 1.0 from every string cell",
            "reason": "CSV and XLSX must contain the same representable text",
            "changed_source_cells": sanitized_cells,
        },
        "inputs": {
            "ready": file_record(ready_path, rows=len(ready)),
            "labels": file_record(labels_path, rows=len(labels)),
            "encoded": file_record(encoded_path, rows=len(encoded)),
            "profile_manifest": file_record(
                frozen_profile_manifest
            ),
            "profile_matches": file_record(
                frozen_profile_matches
            ),
        },
        "membership": file_record(membership_path, rows=len(membership)),
        "profiles": manifest_profiles,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    if not args.skip_xlsx:
        exporter = REPO_ROOT / "export_mixed_profile_workbooks.sh"
        export_command = [str(exporter), str(output_dir)]
        if args.preview_dir is not None:
            export_command.append(str(absolute(args.preview_dir)))
        subprocess.run(export_command, check=True, cwd=REPO_ROOT)
        for profile_record in manifest_profiles:
            xlsx_path = REPO_ROOT / str(profile_record["xlsx"]["path"])
            profile_record["xlsx"] = file_record(xlsx_path, rows=args.sample_size)

    write_readme(
        output_dir,
        readme_profiles,
        seed=args.seed,
        sample_size=args.sample_size,
        threshold=threshold,
        sanitized_cells=sanitized_cells,
    )
    manifest["readme"] = file_record(output_dir / "README.md")
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(
        f"Frozen {len(profiles)} Qwen profiles with {args.sample_size} sampled rows each "
        f"using seed {args.seed}: {output_dir}"
    )
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        raise
